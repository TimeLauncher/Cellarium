// 플레이어가 받은 피해가 어디서 왔는지.
//
// ★ 왜 필요한가 (기획서 Bug Report '대시 시전 무적 조정'):
//   대시 중에는 dashInvincibleTimer가 켜지는데, 예전엔 TakeDamage 맨 앞에서 이 타이머 하나로
//   '모든' 피해를 무시했다. 그래서 대시로 몬스터를 들이받는 동안 투사체와 몬스터 공격까지
//   전부 튕겨내는, 사실상 무적 구간이 생겼다.
//   기댓값은 "몬스터와의 몸통 접촉 피해만 무적, 공격·투사체 피해는 그대로 적용"이므로
//   피해에 출처를 달아서 접촉만 골라 면역시킨다.
public enum DamageSource
{
    // 몬스터 몸통에 겹쳐서 받는 피해 (MonsterBase.CheckContactDamage).
    // 대시로 박는 동안/튕겨나오는 동안 면역되는 것은 이것 하나뿐이다.
    Contact,

    // 몬스터의 공격 판정 — 히트박스, 투사체, 자폭, 덮치기 등. 대시 중에도 그대로 맞는다.
    Attack,

    // 지형 피해 (가시 등). 몬스터가 아니므로 대시 접촉 무적과 무관하게 항상 적용된다.
    Environment,
}
